// Builds apps-script/Code.gs: the app's reminder rules (src/lib, bundled as the global `PM`)
// followed by apps-script/main.js. Paste Code.gs into the Google Apps Script editor.
// Run: npm run apps-script

import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'vite'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'apps-script', '.build')

await build({
  root,
  configFile: false,
  logLevel: 'warn',
  build: {
    outDir,
    emptyOutDir: true,
    minify: false,
    lib: { entry: join(root, 'apps-script', 'entry.js'), name: 'PM', formats: ['iife'], fileName: () => 'pm.js' },
  },
})

const bundle = readFileSync(join(outDir, 'pm.js'), 'utf8')
const main = readFileSync(join(root, 'apps-script', 'main.js'), 'utf8')
const header = `// GENERATED by scripts/build-apps-script.js on ${new Date().toISOString().slice(0, 10)}. Do not edit here:
// edit apps-script/main.js (or src/lib for the reminder rules) and run: npm run apps-script
`
writeFileSync(join(root, 'apps-script', 'Code.gs'), `${header}\n${bundle}\n\n${main}`)
rmSync(outDir, { recursive: true, force: true })
console.log('Wrote apps-script/Code.gs')
